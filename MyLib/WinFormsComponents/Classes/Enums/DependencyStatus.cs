    /// </remarks>
    public enum DependencyStatus
    {
        /// <summary>
        /// Добавлен
        /// </summary>
        /// <value>0</value>
        Insert = 0,
        /// <summary>
        /// Удален
        /// </summary>
        /// <value>1</value>
        Remove = 1,
        /// <summary>
        /// По умолчанию
        /// </summary>
        /// <value>2</value>
        Default = 2
    }
}
